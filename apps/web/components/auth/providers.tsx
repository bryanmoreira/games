/** Mensagens para os códigos de erro que o Better Auth manda em ?error= */
export function errorMessage(code: string): string {
  if (code === "state_mismatch" || code === "state_not_found") return "O login expirou. Tente de novo.";
  if (code === "access_denied") return "Login cancelado.";
  return "Não deu para entrar. Tente de novo.";
}
